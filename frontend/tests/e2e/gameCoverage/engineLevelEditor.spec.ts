import { expect, test } from "@playwright/test";
test.use({ actionTimeout: 15_000 });

test("Lua Engine level integration is separately gated and shares visual edits with scripts", async ({ page }) => {
  test.skip(process.env.PANGEA_SANDBOX_RUNTIME_TEST !== "1", "Stage the engine runtime before running this acceptance test.");
  test.setTimeout(120_000);
  await page.addInitScript(() => { if (!localStorage.getItem("pangea-feature-flags")) localStorage.setItem("pangea-feature-flags", JSON.stringify({ scripting: true })); });
  await page.goto("#/engine/levels");
  await expect(page.getByRole("link", { name: "Lua Engine", exact: true })).toHaveCount(0);
  await expect(page.getByRole("link", { name: "Open engine level editor", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Open settings", exact: true }).click();
  await page.getByRole("menuitemcheckbox", { name: /^Lua Engine level editor/ }).click();
  await page.keyboard.press("Escape");
  await page.getByRole("link", { name: "Open engine level editor", exact: true }).click();
  await page.getByRole("combobox", { name: "Scene", exact: true }).selectOption("scenes/scene.json");
  await page.getByLabel("Sample height", { exact: true }).fill("25");
  await page.getByRole("button", { name: "Open settings", exact: true }).click();
  await expect(page.getByRole("menuitemcheckbox", { name: /^Lua Engine level editor/ })).toBeDisabled();
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Undo", exact: true }).click();
  await expect(page.getByLabel("Sample height", { exact: true })).toHaveValue("0");
  await page.getByRole("button", { name: "Redo", exact: true }).click();
  await expect(page.getByLabel("Sample height", { exact: true })).toHaveValue("25");
  await page.getByLabel("Sample column", { exact: true }).fill("1");
  await page.getByLabel("Sample row", { exact: true }).fill("1");
  await expect(page.getByLabel("Sample height", { exact: true })).toHaveValue("0");
  await page.getByRole("button", { name: "Raise", exact: true }).click();
  const terrain = page.getByLabel("Engine terrain heightfield", { exact: true });
  const terrainBounds = await terrain.boundingBox();
  expect(terrainBounds).not.toBeNull();
  if (!terrainBounds) return;
  await terrain.click({ position: { x: terrainBounds.width * .75, y: terrainBounds.height * .75 } });
  await expect(page.getByLabel("Sample height", { exact: true })).toHaveValue("25");
  await page.getByRole("button", { name: "Move boxes", exact: true }).click();
  const wall = page.locator('svg[aria-label="Scene actors and collision boxes"] rect').first();
  await wall.scrollIntoViewIfNeeded();
  const bounds = await wall.boundingBox();
  expect(bounds).not.toBeNull();
  if (!bounds) return;
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
  await page.mouse.down(); await page.mouse.move(bounds.x + bounds.width / 2 + 20, bounds.y + bounds.height / 2); await page.mouse.up();
  await expect(page.getByLabel("Position X", { exact: true }).first()).not.toHaveValue("400");
  await page.getByRole("button", { name: "Undo", exact: true }).click();
  await expect(page.getByLabel("Position X", { exact: true }).first()).toHaveValue("400");
  await expect(page.getByRole("button", { name: "Preview level", exact: true })).toBeEnabled({ timeout: 60_000 });
  await page.getByRole("button", { name: "Preview level", exact: true }).click();
  const preview = page.frameLocator('iframe[title="Lua engine preview"]');
  await expect(preview.getByRole("heading", { name: "Engine foundation", exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Package & scripts", exact: true }).click();
  await expect(page.getByRole("heading", { level: 1 })).toContainText("*");
  await page.getByRole("link", { name: "Edit levels", exact: true }).click();
  await expect(page.getByLabel("Sample height", { exact: true })).toHaveValue("25");
  await expect(page.getByRole("button", { name: "Preview level", exact: true })).toBeEnabled({ timeout: 60_000 });
  await page.setViewportSize({ width: 900, height: 700 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: "/tmp/pangea-engine-level-editor.png" });
});

test("an existing Otto level previews its floor in Lua Engine without closing the source editor", async ({ page }) => {
  test.skip(process.env.PANGEA_SANDBOX_RUNTIME_TEST !== "1", "Stage the engine runtime before running this acceptance test.");
  test.setTimeout(120_000);
  await page.addInitScript(() => localStorage.setItem("pangea-feature-flags", JSON.stringify({ luaEngine: true })));
  await page.goto("#/");
  await page.getByRole("button", { name: "Create Blank Level", exact: true }).first().click();
  await page.getByRole("button", { name: "Level Actions", exact: true }).click();
  await page.getByRole("menuitem", { name: "Preview terrain in Lua Engine", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog).toContainText("Your original level stays open.", { timeout: 30_000 });
  const preview = page.frameLocator('iframe[title="Lua engine terrain preview"]');
  await expect(preview.getByRole("heading", { name: "Terrain test", exact: true })).toBeVisible({ timeout: 60_000 });
  const downloaded = page.waitForEvent("download");
  await dialog.getByRole("button", { name: "Download terrain package", exact: true }).click();
  expect((await downloaded).suggestedFilename()).toBe("pangea-game.zip");
  await dialog.getByRole("button", { name: "Close", exact: true }).click();
  await expect(page.getByRole("button", { name: "Level Actions", exact: true })).toBeVisible();
});
