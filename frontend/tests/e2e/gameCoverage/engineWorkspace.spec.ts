import { expect, test } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { unzipSync } from "fflate";
import { ResultAsync } from "neverthrow";

test("Lua engine workspace runs, edits and exports the real Foundation package", async ({ page }) => {
  test.skip(process.env.PANGEA_SANDBOX_RUNTIME_TEST !== "1", "Build and stage PangeaSandbox to run engine acceptance tests.");
  test.setTimeout(120_000);
  const failures: string[] = [];
  page.on("pageerror", (error) => failures.push(error.message));
  await page.addInitScript(() => localStorage.setItem("pangea-feature-flags", JSON.stringify({ luaEngine: true })));
  await page.goto("#/engine");
  const preview = page.frameLocator('iframe[title="Lua engine preview"]');
  await expect(preview.getByRole("heading", { name: "Engine foundation", exact: true })).toBeVisible({ timeout: 60_000 });
  await expect(page.getByRole("button", { name: "Run changes" })).toBeEnabled();
  await expect(page.getByText(/scene ·/)).toBeVisible();
  await preview.getByRole("button", { name: "Pause", exact: true }).click();
  await expect(preview.getByRole("button", { name: "Resume", exact: true })).toBeVisible();
  await expect(page.getByText(/scene · paused/)).toBeVisible();
  await preview.getByRole("button", { name: "Resume", exact: true }).click();
  await preview.locator("canvas").focus();
  await page.keyboard.press("Escape");
  await expect(preview.getByRole("button", { name: "Resume", exact: true })).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(preview.getByRole("button", { name: "Pause", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "scenes/scene.json", exact: true }).click();
  await page.getByText("Scene properties", { exact: true }).click();
  await page.getByLabel("Cells per chunk", { exact: true }).fill("32");
  await page.getByRole("button", { name: "Run changes" }).click();
  await expect(page.getByRole("status")).toContainText("Preview updated.");
  await expect(page.getByText(/scene ·/)).toBeVisible();
  await expect(preview.getByRole("button", { name: "Pause", exact: true })).toBeVisible();
  await page.getByLabel("Scene ID", { exact: true }).fill("courtyard");
  await page.getByLabel("Display name", { exact: true }).fill("Courtyard");
  await page.getByRole("button", { name: "Create scene + controller" }).click();
  await page.getByRole("combobox", { name: "Start scene", exact: true }).selectOption("courtyard");
  await page.getByRole("button", { name: "Run changes", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Preview updated.");
  await page.getByRole("combobox", { name: "Preview scene", exact: true }).selectOption("courtyard");
  await expect(page.getByText(/courtyard ·/)).toBeVisible();
  await page.getByRole("combobox", { name: "Preview scene", exact: true }).selectOption("scene");
  await expect(preview.getByRole("button", { name: "Pause", exact: true })).toBeVisible();
  const downloadEvent = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download package", exact: true }).click();
  const download = await downloadEvent;
  const file = await download.path();
  expect(file).toBeTruthy();
  if (!file) return;
  const bytes = await ResultAsync.fromPromise(readFile(file), String);
  expect(bytes.isOk()).toBe(true);
  if (bytes.isErr()) return;
  const archive = unzipSync(bytes.value);
  expect(archive["schemas/package.schema.json"]).toBeDefined();
  expect(archive["schemas/scene.schema.json"]).toBeDefined();
  expect(archive["types/engine.lua"]).toBeDefined();
  expect(archive["scenes/courtyard.lua"]).toBeDefined();
  await page.getByLabel("Game name", { exact: true }).fill("Edited Workshop");
  await page.getByRole("link", { name: "Model Viewer", exact: true }).click();
  await expect(page.getByRole("dialog")).toContainText("Download package before leaving?");
  await page.getByRole("button", { name: "Keep editing", exact: true }).click();
  await expect(page.getByRole("dialog")).not.toBeVisible();
  await page.setViewportSize({ width: 900, height: 700 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.screenshot({ path: "/tmp/pangea-engine-workspace.png" });
  expect(failures).toEqual([]);
});
