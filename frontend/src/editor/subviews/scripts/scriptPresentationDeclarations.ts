export function presentationParameterType(namespace: string, method: string, parameter: string): string | undefined {
  if (!["ui", "dialogue", "audio", "effects"].includes(namespace)) return undefined;
  if (parameter === "handle") return "PresentationHandle";
  if (parameter === "nodes") return "DialogueNode[]";
  if (parameter === "options") return namespace === "ui" && method === "objective" ? "ObjectiveOptions" : "PresentationOptions";
  return undefined;
}

