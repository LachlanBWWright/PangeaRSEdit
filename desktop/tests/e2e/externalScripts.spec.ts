import * as fs from "node:fs/promises";
import path from "node:path";
import { test, expect } from "./desktopFixture.ts";
import { replySchema, projectSnapshotSchema } from "@pangea/desktop-contracts";

test("desktop object behavior opens externally and reloads saved Lua without mounting Monaco", async ({ desktop }) => {
  const { application, page, folder } = desktop;
  await application.evaluate(({ dialog }, selected) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [selected] }); }, folder);
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /New Project/ }).click();
  await page.getByLabel("Name", { exact: true }).fill("External scripts");
  await page.getByRole("button", { name: "Choose folder and create" }).click();
  await expect(page.getByRole("dialog")).not.toBeVisible();
  await page.goto("pangea://editor/index.html#/custom-objects");
  await expect(page.getByRole("button", { name: "New object", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "New object", exact: true }).click();
  await page.getByLabel("Object name", { exact: true }).fill("Checkpoint lantern");
  await page.getByRole("button", { name: "Create object", exact: true }).click();
  await page.getByRole("button", { name: "Edit behavior", exact: true }).click();
  await expect(page.getByLabel("Lua source preview", { exact: true })).toBeVisible();
  await expect(page.locator(".monaco-editor")).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Open file externally", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /Save All/ }).click();
  await expect(page.getByText("Project scripts saved", { exact: true })).toBeVisible();
  await expect(page.getByRole("menu")).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Open file externally", exact: true })).toBeEnabled();
  const response = replySchema(projectSnapshotSchema).safeParse(await page.evaluate(() => window.pangeaDesktop?.request({ operation: "project.inspect" })));
  expect(response.success && response.data.ok).toBe(true);
  if (!response.success || !response.data.ok) return;
  const source = response.data.value.files.find((file) => file.path.startsWith("Data/Scripts/src/") && file.path.includes("checkpoint"));
  expect(source).toBeDefined();
  if (!source) return;
  await application.evaluate(({ app, shell }) => {
    app.getApplicationNameForProtocol = () => "VSCodium";
    shell.openExternal = async (url) => { process.env.PANGEA_LAST_EDITOR_URL = url; };
  });
  await page.setViewportSize({ width: 1000, height: 600 });
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await expect(page.getByRole("menu")).toBeVisible();
  await expect.poll(async () => {
    const bounds = await page.getByRole("menu").boundingBox();
    return bounds ? bounds.y + bounds.height : Number.POSITIVE_INFINITY;
  }).toBeLessThanOrEqual(600);
  await page.getByRole("menuitem", { name: /Project Settings/ }).click();
  await page.getByRole("combobox", { name: /^Preferred external editor/ }).selectOption("vscodium");
  await expect(page.getByRole("combobox", { name: /^Preferred external editor/ })).toBeEnabled();
  await page.getByRole("button", { name: "Done", exact: true }).click();
  await page.getByRole("button", { name: "Open file externally", exact: true }).click();
  await expect.poll(() => application.evaluate(() => process.env.PANGEA_LAST_EDITOR_URL)).toContain("vscodium://file/");
  const opened = await page.evaluate((relative) => window.pangeaDesktop?.request({ operation: "project.external", path: relative, action: "edit", line: 42 }), source.path);
  expect(opened).toMatchObject({ ok: true });
  expect(await application.evaluate(() => process.env.PANGEA_LAST_EDITOR_URL)).toContain(":42:1");
  const location = path.join(folder, source.path);
  const original = await fs.readFile(location, "utf8");
  await fs.writeFile(location, `${original}\n-- External editor synchronization marker\n`);
  await expect(page.getByLabel("Lua source preview", { exact: true })).toContainText("External editor synchronization marker", { timeout: 15_000 });
  await expect(page.getByLabel("Unsaved changes", { exact: true })).not.toBeVisible();
});
