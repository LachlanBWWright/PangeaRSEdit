import * as fs from "node:fs/promises";
import path from "node:path";
import { test, expect } from "./desktopFixture.ts";
import { replySchema, projectSnapshotSchema } from "@pangea/desktop-contracts";
import { unzipSync } from "fflate";
import { assignPalette } from "./assetAssignmentFixture.ts";

test("exports saved native levels into a playable pack, verifies it, and imports the editable project", async ({ desktop }) => {
  const { page, application, folder } = desktop;
  const archive = path.join(path.dirname(folder), "missions.pangeapack");
  const destination = path.join(path.dirname(folder), "imported");
  await fs.mkdir(destination);
  await application.evaluate(({ dialog }, selected) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [selected] }); }, folder);
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /New Project/ }).click();
  await page.getByLabel("Name", { exact: true }).fill("Playable missions");
  await page.getByRole("button", { name: "Choose folder and create" }).click();
  await expect(page.getByRole("dialog")).not.toBeVisible();
  await page.getByRole("button", { name: "Create Blank Level", exact: true }).first().click();
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /Save All/ }).click();
  await expect(page.getByLabel("Unsaved changes", { exact: true })).not.toBeVisible({ timeout: 30000 });
  await assignPalette(page, application, folder);
  await application.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }); }, archive);
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /Playable Packs/ }).click();
  const packDialog = page.getByRole("dialog", { name: "Playable packs", exact: true });
  await packDialog.getByRole("checkbox", { name: "Include editable project", exact: true }).check();
  await packDialog.getByRole("button", { name: "Export current project", exact: true }).click();
  await expect(packDialog.getByRole("status")).toContainText("Playable pack exported", { timeout: 30000 });
  expect((await fs.stat(archive)).size).toBeGreaterThan(0);
  const contents = unzipSync(await fs.readFile(archive));
  const assigned = Object.entries(contents).find(([name]) => name.startsWith("Runtime/") && name.endsWith("/Data/Images/farm.tga"))?.[1];
  expect(assigned?.subarray(18, 786)).toEqual(new Uint8Array(768).fill(93));
  expect(assigned?.subarray(786)).toEqual(new Uint8Array([13, 72]));
  await application.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, archive);
  await page.getByRole("button", { name: "Open playable pack", exact: true }).click();
  await expect(packDialog.getByRole("status")).toContainText("Pack integrity verified");
  await expect(page.getByRole("combobox", { name: "Pack level", exact: true })).toBeVisible();
  await application.evaluate(({ dialog }, selected) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [selected] }); }, destination);
  await page.getByRole("button", { name: "Import editable project", exact: true }).click();
  await expect(page.getByText("Editable pack project imported", { exact: true })).toBeVisible();
  const result = replySchema(projectSnapshotSchema).safeParse(await page.evaluate(() => window.pangeaDesktop?.request({ operation: "project.inspect" })));
  expect(result.success && result.data.ok).toBe(true);
  if (!result.success || !result.data.ok) return;
  expect(result.data.value.folder).toBe(destination);
  expect(result.data.value.manifest.levels).toHaveLength(1);
});
