import { test, expect } from "./desktopFixture.ts";
import * as fs from "node:fs/promises";
import path from "node:path";
import { Result, ResultAsync } from "neverthrow";
import { projectManifestSchema, type DesktopBridge } from "@pangea/desktop-contracts";

declare global { interface Window { pangeaDesktop?: DesktopBridge } }

test("desktop starts securely, binds a folder, saves a custom level, and reopens it", async ({ desktop }, testInfo) => {
  const { application, page, folder } = desktop;
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.waitForLoadState();
  await expect(page.getByRole("button", { name: "Project menu", exact: true })).toBeVisible();
  await expect(page.getByRole("banner", { name: "Application title bar" }).getByRole("button", { name: "Project menu" })).toBeVisible();
  expect(await application.evaluate(({ Menu }) => Menu.getApplicationMenu())).toBeNull();
  const preferences = await page.evaluate(() => ({ ...window.pangeaDesktop?.security, nodeIntegration: Reflect.has(window, "require") }));
  expect(preferences).toEqual({ nodeIntegration: false, contextIsolated: true, sandboxed: true });
  await application.evaluate(({ dialog }, selectedFolder) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [selectedFolder] });
  }, folder);
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /New Project/ }).click();
  await page.getByLabel("Name", { exact: true }).fill("Desktop integration project");
  await page.getByRole("button", { name: "Choose folder and create" }).click();
  await expect(page.getByText("Desktop integration project", { exact: true })).toBeVisible();
  await expect(page.getByRole("dialog")).not.toBeVisible();
  await page.getByRole("button", { name: "Create Blank Level", exact: true }).first().click();
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await expect(page.getByRole("menuitem", { name: /Save All/ })).toBeEnabled();
  await page.keyboard.press("Escape");
  await application.evaluate(({ BrowserWindow }) => {
    const contents = BrowserWindow.getAllWindows()[0]?.webContents;
    contents?.sendInputEvent({ type: "keyDown", keyCode: "S", modifiers: [process.platform === "darwin" ? "meta" : "control"] });
    contents?.sendInputEvent({ type: "keyUp", keyCode: "S" });
  });
  await expect(page.getByText("Project saved", { exact: true })).toBeVisible({ timeout: 30_000 });
  await expect(page.getByText("Desktop integration project • Unsaved", { exact: true })).not.toBeVisible();
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /Open Project/ }).click();
  await expect(page.getByRole("menu")).not.toBeVisible();
  await expect(page.getByRole("button", { name: "Level Actions", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /Project Settings/ }).click();
  await page.getByRole("combobox", { name: "Native base level" }).selectOption("1");
  await page.getByRole("button", { name: "Done", exact: true }).click();
  await expect(page.getByLabel("Unsaved changes", { exact: true })).toBeVisible();
  await ResultAsync.fromPromise(fs.writeFile(path.join(folder, "external-note.txt"), "Keep this external edit"), () => "External edit failed");
  await expect(page.getByRole("dialog", { name: "Project changed outside the editor" })).toBeVisible({ timeout: 10_000 });
  await expect(page.getByText("Added: external-note.txt", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Keep reviewing", exact: true }).click();
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /Save All/ }).click();
  await expect(page.getByRole("dialog", { name: "Project changed outside the editor" })).toBeVisible();
  await page.getByRole("button", { name: "Keep editor edits for next save", exact: true }).click();
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /Save All/ }).click();
  await expect(page.getByLabel("Unsaved changes", { exact: true })).not.toBeVisible({ timeout: 30_000 });
  const external = await ResultAsync.fromPromise(fs.readFile(path.join(folder, "external-note.txt"), "utf8"), () => "Cannot read external edit");
  expect(external.isOk() && external.value).toBe("Keep this external edit");
  await expect(page.getByRole("menu")).not.toBeVisible();
  await page.getByRole("button", { name: "←New Map", exact: true }).click();
  await page.getByRole("button", { name: "Yes, go back", exact: true }).click();
  await page.getByRole("button", { name: "Create Blank Level", exact: true }).first().click();
  await expect(page.getByLabel("Unsaved changes", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /Save All/ }).click();
  await expect(page.getByLabel("Unsaved changes", { exact: true })).not.toBeVisible({ timeout: 30_000 });
  const text = await ResultAsync.fromPromise(fs.readFile(path.join(folder, "pangea.project.json"), "utf8"), () => "Cannot read project");
  expect(text.isOk()).toBe(true);
  if (text.isErr()) return;
  const json = Result.fromThrowable((): unknown => JSON.parse(text.value), () => "Invalid manifest")();
  expect(json.isOk()).toBe(true);
  if (json.isErr()) return;
  const manifest = projectManifestSchema.safeParse(json.value);
  expect(manifest.success).toBe(true);
  if (!manifest.success) return;
  expect(manifest.data.levels).toHaveLength(2);
  const firstLevel = manifest.data.levels[0];
  expect(firstLevel?.baseLevel).toBe(1);
  if (!firstLevel) return;
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /Project Levels/ }).click();
  await page.getByRole("dialog", { name: "Project levels" }).getByRole("button", { name: firstLevel.name, exact: true }).first().click();
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /Project Settings/ }).click();
  await expect(page.getByRole("combobox", { name: "Native base level" })).toHaveValue("1");
  await page.getByRole("button", { name: "Done", exact: true }).click();
  await expect(page.getByLabel("Unsaved changes", { exact: true })).not.toBeVisible();
  const screenshot = testInfo.outputPath("project-created.png");
  await page.screenshot({ path: screenshot, fullPage: true });
  await testInfo.attach("Saved project", { path: screenshot, contentType: "image/png" });
  await ResultAsync.fromPromise(fs.rm(path.join(folder, firstLevel.primary)), () => "External deletion failed");
  await expect(page.getByText("The level file was deleted outside the editor. The document was closed.", { exact: true })).toBeVisible({ timeout: 10_000 });
  await expect(page.getByRole("button", { name: "Create Blank Level", exact: true }).first()).toBeVisible();
  expect(errors).toEqual([]);
});
