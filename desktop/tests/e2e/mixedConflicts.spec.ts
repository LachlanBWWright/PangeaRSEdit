import * as fs from "node:fs/promises";
import path from "node:path";
import { test, expect } from "./desktopFixture.ts";
import { replySchema, projectSnapshotSchema } from "@pangea/desktop-contracts";

test("mixed-file review keeps local object metadata and reloads external Lua and binary additions", async ({ desktop }) => {
  const { page, application, folder } = desktop;
  await application.evaluate(({ dialog }, selected) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [selected] }); }, folder);
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /New Project/ }).click();
  await page.getByLabel("Name", { exact: true }).fill("Mixed changes");
  await page.getByRole("button", { name: "Choose folder and create" }).click();
  await expect(page.getByRole("dialog")).not.toBeVisible();
  await page.goto("pangea://editor/index.html#/custom-objects");
  await page.getByRole("button", { name: "New object", exact: true }).click();
  await page.getByLabel("Object name", { exact: true }).fill("Checkpoint lantern");
  await page.getByRole("button", { name: "Create object", exact: true }).click();
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /Save All/ }).click();
  await expect(page.getByText("Project scripts saved", { exact: true })).toBeVisible();
  await page.getByLabel("Object name", { exact: true }).fill("Local lantern name");
  await expect(page.getByLabel("Unsaved changes", { exact: true })).toBeVisible();
  const inspected = replySchema(projectSnapshotSchema).safeParse(await page.evaluate(() => window.pangeaDesktop?.request({ operation: "project.inspect" })));
  if (!inspected.success || !inspected.data.ok) return;
  const source = inspected.data.value.files.find((file) => file.path.startsWith("Data/Scripts/src/") && file.path.includes("checkpoint"));
  expect(source).toBeDefined(); if (!source) return;
  await fs.appendFile(path.join(folder, source.path), "\n-- Mixed review disk marker\n");
  await fs.mkdir(path.join(folder, "Assets"), { recursive: true });
  await fs.writeFile(path.join(folder, "Assets/external.png"), new Uint8Array([0, 17, 255]));
  const dialog = page.getByRole("dialog", { name: "Project changed outside the editor", exact: true });
  await expect(dialog).toBeVisible({ timeout: 10000 });
  await expect(dialog.getByText("Added: Assets/external.png", { exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: "Review and merge files", exact: true }).click();
  await expect(dialog.getByRole("button", { name: "Apply merged files and reload", exact: true })).toBeEnabled();
  await dialog.getByRole("button", { name: "Apply merged files and reload", exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByLabel("Object name", { exact: true })).toHaveValue("Local lantern name");
  await page.getByRole("button", { name: "Edit behavior", exact: true }).click();
  await expect(page.getByLabel("Lua source preview", { exact: true })).toContainText("Mixed review disk marker");
  await expect(page.getByLabel("Unsaved changes", { exact: true })).not.toBeVisible();
  expect(await fs.readFile(path.join(folder, "Assets/external.png"))).toEqual(Buffer.from([0, 17, 255]));
});
