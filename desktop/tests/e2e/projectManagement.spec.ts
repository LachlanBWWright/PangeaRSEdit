import * as fs from "node:fs/promises";
import path from "node:path";
import { test, expect } from "./desktopFixture.ts";
import { projectSnapshotSchema, replySchema } from "@pangea/desktop-contracts";

test("manages levels, browses files, copies a project and restores the selected level after restart", async ({ desktop }) => {
  let page = desktop.page;
  await desktop.application.evaluate(({ dialog }, folder) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [folder] });
  }, desktop.folder);
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /New Project/ }).click();
  await page.getByLabel("Name", { exact: true }).fill("Managed pack");
  await page.getByRole("button", { name: "Choose folder and create" }).click();
  await expect(page.getByRole("dialog")).not.toBeVisible();
  await page.getByRole("button", { name: "Create Blank Level", exact: true }).first().click();
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /Save All/ }).click();
  await expect(page.getByLabel("Unsaved changes", { exact: true })).not.toBeVisible({ timeout: 30_000 });
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /Project Levels/ }).click();
  await page.getByLabel("Level name", { exact: true }).fill("Opening scene");
  await page.getByRole("button", { name: "Rename", exact: true }).click();
  await expect(page.getByRole("button", { name: "Opening scene", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Duplicate", exact: true }).click();
  await expect(page.getByRole("button", { name: "Opening scene copy", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Move up", exact: true }).nth(1).click();
  await page.getByRole("button", { name: "Opening scene copy", exact: true }).click();
  await expect(page.getByText("Project level opened", { exact: true })).toBeVisible();
  await expect(page.getByLabel("Unsaved changes", { exact: true })).not.toBeVisible();
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /Project Files/ }).click();
  await page.getByLabel("Filter files", { exact: true }).fill("bindings.json");
  await expect(page.getByRole("button", { name: "Reveal", exact: true })).toHaveCount(2);
  await page.getByRole("dialog", { name: "Project files", exact: true }).getByRole("button", { name: "Close", exact: true }).click();
  await expect(page.getByRole("dialog")).not.toBeVisible();
  const destination = `${desktop.folder}-copy`;
  await fs.mkdir(destination);
  await desktop.application.evaluate(({ dialog }, folder) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [folder] });
  }, destination);
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /Save Project As/ }).click();
  await expect(page.getByText("Project saved to the new folder", { exact: true })).toBeVisible();
  const reply = await page.evaluate(() => window.pangeaDesktop?.request({ operation: "project.inspect" }));
  const parsed = replySchema(projectSnapshotSchema).safeParse(reply);
  expect(parsed.success && parsed.data.ok).toBe(true);
  if (!parsed.success || !parsed.data.ok) return;
  expect(parsed.data.value.folder).toBe(destination);
  expect(parsed.data.value.manifest.levels.map((level) => level.name)).toEqual(["Opening scene copy", "Opening scene"]);
  expect(await fs.readFile(path.join(destination, "pangea.project.json"), "utf8")).toContain("Opening scene copy");
  const resumed = await desktop.restart();
  expect(resumed).not.toBeNull();
  if (!resumed) return;
  page = resumed.page;
  await expect(page.getByText("Project level opened", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /Project Levels/ }).click();
  await expect(page.getByRole("button", { name: "Opening scene copy", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.getByRole("button", { name: "Delete", exact: true }).nth(1).click();
  await page.getByRole("button", { name: "Confirm delete", exact: true }).click();
  await expect(page.getByLabel("Level name", { exact: true })).toHaveCount(1);
  await fs.rm(destination, { recursive: true, force: true });
});
