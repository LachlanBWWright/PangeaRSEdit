import * as fs from "node:fs/promises";
import path from "node:path";
import { z } from "zod";
import { projectAssetSchema, projectSnapshotSchema, replySchema } from "@pangea/desktop-contracts";
import { test, expect } from "./desktopFixture.ts";
import { customItemModelFixture } from "./customItemModelFixture.ts";

test("imports an animated shared model, places its enemy through Konva, and preserves it across reimport and restart", async ({ desktop }) => {
  test.setTimeout(120_000);
  let page = desktop.page;
  const { application, folder } = desktop;
  await application.evaluate(({ dialog }, selected) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [selected] });
  }, folder);
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /New Project/ }).click();
  await page.getByLabel("Name", { exact: true }).fill("Custom item acceptance");
  await page.getByRole("button", { name: "Choose folder and create", exact: true }).click();
  await expect(page.getByRole("dialog")).not.toBeVisible();
  await page.getByRole("button", { name: "Create Blank Level", exact: true }).first().click();
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /Save All/ }).click();
  await expect(page.getByLabel("Unsaved changes", { exact: true })).not.toBeVisible();
  const initial = replySchema(projectSnapshotSchema).safeParse(await page.evaluate(() => window.pangeaDesktop?.request({ operation: "project.inspect" })));
  expect(initial.success && initial.data.ok).toBe(true);
  if (!initial.success || !initial.data.ok) return;
  expect(initial.data.value.manifest.levels).toHaveLength(1);
  await page.goto("pangea://editor/index.html#/custom-objects");
  await page.getByRole("button", { name: "New object", exact: true }).click();
  await page.getByRole("dialog", { name: "New custom object", exact: true }).getByLabel("Object name", { exact: true }).fill("Acceptance robot");
  await page.getByRole("radio", { name: /^Enemy/ }).check();
  await page.getByRole("button", { name: "Create object", exact: true }).click();
  await page.getByRole("combobox", { name: "Appearance", exact: true }).click();
  await page.getByRole("option", { name: "Project model", exact: true }).click();
  const source = path.join(path.dirname(folder), "robot.glb");
  await fs.writeFile(source, customItemModelFixture());
  await application.evaluate(({ dialog }, selected) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [selected] });
  }, source);
  await page.getByLabel("Asset name", { exact: true }).fill("Robot appearance");
  await page.getByRole("button", { name: "Import model…", exact: true }).click();
  await expect(page.getByRole("button", { name: "Used by this object", exact: true })).toBeVisible({ timeout: 30_000 });
  const listed = replySchema(z.array(projectAssetSchema)).safeParse(await page.evaluate(() => window.pangeaDesktop?.request({ operation: "assets.list" })));
  expect(listed.success && listed.data.ok).toBe(true);
  if (!listed.success || !listed.data.ok) return;
  const asset = listed.data.value[0];
  expect(asset).toBeDefined();
  if (!asset) return;
  expect(asset.animations.map((clip) => clip.name)).toEqual(["Idle", "Walk"]);
  expect(asset.outputs.skeleton).toMatch(/\.skeleton\.rsrc$/);
  expect((await fs.stat(path.join(folder, asset.outputs.model))).size).toBeGreaterThan(0);
  await page.getByRole("button", { name: "New object", exact: true }).click();
  await page.getByRole("dialog", { name: "New custom object", exact: true }).getByLabel("Object name", { exact: true }).fill("Acceptance sibling");
  await page.getByRole("radio", { name: /^Enemy/ }).check();
  await page.getByRole("button", { name: "Create object", exact: true }).click();
  await page.getByRole("combobox", { name: "Appearance", exact: true }).click();
  await page.getByRole("option", { name: "Project model", exact: true }).click();
  await page.getByRole("combobox", { name: "Project model", exact: true }).selectOption(asset.id);
  await page.getByRole("button", { name: "Use this asset", exact: true }).click();
  await expect(page.getByText(/Used by Acceptance robot.*Acceptance sibling/)).toBeVisible();
  await page.getByRole("button", { name: /Acceptance robot/ }).click();
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /Save All/ }).click();
  await expect(page.getByLabel("Unsaved changes", { exact: true })).not.toBeVisible();
  await page.getByRole("button", { name: "Place in level", exact: true }).click();
  await expect(page.getByRole("tab", { name: "Items", exact: true })).toHaveAttribute("data-state", "active");
  const canvas = page.locator("canvas").last();
  await expect(canvas).toBeVisible();
  const box = await canvas.boundingBox();
  expect(box).not.toBeNull();
  if (!box) return;
  const position = { x: Math.floor(box.width / 2), y: Math.floor(box.height / 2) };
  await canvas.click({ position });
  await page.getByRole("button", { name: "Stop Adding Items", exact: true }).click();
  await canvas.click({ position });
  await expect(page.getByLabel("Health", { exact: true })).toBeVisible();
  await page.getByLabel("Health", { exact: true }).fill("3");
  await expect(page.getByText("Placement override", { exact: true }).first()).toBeVisible();
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /Save All/ }).click();
  await expect(page.getByLabel("Unsaved changes", { exact: true })).not.toBeVisible({ timeout: 30_000 });
  const saved = replySchema(projectSnapshotSchema).safeParse(await page.evaluate(() => window.pangeaDesktop?.request({ operation: "project.inspect" })));
  expect(saved.success && saved.data.ok).toBe(true);
  if (!saved.success || !saved.data.ok) return;
  const sources = await Promise.all(saved.data.value.files.filter((file) => file.path.startsWith("Data/Scripts/src/") && file.path.endsWith(".lua"))
    .map(async (file) => ({ path: file.path, bytes: await fs.readFile(path.join(folder, file.path)) })));
  expect(sources.length).toBeGreaterThanOrEqual(2);

  const managedSource = path.join(folder, asset.source.path);
  await fs.writeFile(managedSource, customItemModelFixture(125));
  await expect.poll(async () => {
    const result = replySchema(z.array(projectAssetSchema)).safeParse(await page.evaluate(() => window.pangeaDesktop?.request({ operation: "assets.list" })));
    return result.success && result.data.ok ? result.data.value[0]?.revision : asset.revision;
  }, { timeout: 20_000 }).not.toBe(asset.revision);
  const resumed = await desktop.restart();
  expect(resumed).not.toBeNull();
  if (!resumed) return;
  page = resumed.page;
  for (const file of sources) expect(await fs.readFile(path.join(folder, file.path))).toEqual(file.bytes);
  await page.getByRole("tab", { name: "Items", exact: true }).click();
  await page.locator("canvas").last().click({ position });
  await expect(page.getByLabel("Health", { exact: true })).toHaveValue("3");
  await page.goto("pangea://editor/index.html#/custom-objects");
  await page.getByRole("button", { name: /Acceptance robot/ }).click();
  await expect(page.getByRole("combobox", { name: "Project model", exact: true })).toHaveValue(asset.id);
  await expect(page.getByRole("button", { name: "Used by this object", exact: true })).toBeVisible();
  await page.getByRole("button", { name: /Acceptance sibling/ }).click();
  await expect(page.getByRole("combobox", { name: "Project model", exact: true })).toHaveValue(asset.id);

  const bundle = path.join(path.dirname(folder), "editable-objects.zip");
  await resumed.application.evaluate(({ session }, destination) => {
    process.env.PANGEA_CUSTOM_OBJECT_EXPORT = "waiting";
    session.defaultSession.once("will-download", (_event, item) => {
      item.setSavePath(destination);
      item.once("done", (_event, state) => { process.env.PANGEA_CUSTOM_OBJECT_EXPORT = state; });
    });
  }, bundle);
  await page.getByRole("checkbox", { name: "Include authoring sources", exact: true }).check();
  await page.getByRole("button", { name: "Export objects", exact: true }).click();
  await expect.poll(async () => {
    const alerts = await page.getByRole("alert").allTextContents();
    return alerts.length ? alerts.join("\n") : resumed.application.evaluate(() => process.env.PANGEA_CUSTOM_OBJECT_EXPORT);
  }, { timeout: 30_000 }).toBe("completed");
  expect((await fs.stat(bundle)).size).toBeGreaterThan(0);
  const destination = path.join(path.dirname(folder), "fresh-project");
  await fs.mkdir(destination);
  await resumed.application.evaluate(({ dialog }, selected) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [selected] });
  }, destination);
  await page.getByRole("button", { name: "Project menu", exact: true }).click();
  await page.getByRole("menuitem", { name: /New Project/ }).click();
  await page.getByLabel("Name", { exact: true }).fill("Editable bundle recipient");
  await page.getByRole("button", { name: "Choose folder and create", exact: true }).click();
  await expect(page.getByRole("dialog")).not.toBeVisible();
  await page.goto("pangea://editor/index.html#/custom-objects");
  await page.getByLabel("Import objects", { exact: true }).setInputFiles(bundle);
  await expect(page.getByRole("combobox", { name: "Project model", exact: true })).toHaveValue(asset.id);
  const imported = replySchema(z.array(projectAssetSchema)).safeParse(await page.evaluate(() => window.pangeaDesktop?.request({ operation: "assets.list" })));
  expect(imported.success && imported.data.ok).toBe(true);
  if (!imported.success || !imported.data.ok) return;
  const restored = imported.data.value.find((item) => item.id === asset.id);
  expect(restored).toBeDefined();
  if (!restored) return;
  expect(restored.source.mode).toBe("managed");
  expect(await fs.readFile(path.join(destination, restored.source.path))).toEqual(Buffer.from(customItemModelFixture(125)));
  expect(restored.animations.map((clip) => clip.name)).toEqual(["Idle", "Walk"]);
});
